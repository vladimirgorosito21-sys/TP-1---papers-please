const ACCENTS = {
  "Á": ["A", "acute"], "É": ["E", "acute"], "Í": ["I", "acute"],
  "Ó": ["O", "acute"], "Ú": ["U", "acute"], "Ñ": ["N", "tilde"]
};

const GLYPHS = {};
for (const k of Object.keys(RAW)) {
  const rows = RAW[k].split("|");
  GLYPHS[k] = { w: rows[0].length, rows };
}

function glyph(ch) {
  const up = ch.toUpperCase();
  if (ACCENTS[up]) return { base: GLYPHS[ACCENTS[up][0]], accent: ACCENTS[up][1] };
  return { base: GLYPHS[up] || GLYPHS["?"], accent: null };
}

/* Ancho total del texto en píxeles (scale 1) */
function measure(str, spacing = 1) {
  let w = 0;
  for (const ch of str) w += glyph(ch).base.w + spacing;
  return w - spacing;
}

module.exports = { glyph, measure, HEIGHT: 7 };
